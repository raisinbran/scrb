import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { evaluate, VARIANTS } from './evaluate.js';
import { AMI_TUNED } from './tuned.js';

/**
 * Usage: tsx eval/run.ts [amiAnnotationDir] [outFile]
 * AMI annotations stay outside git. Only AMI data and invented headings are used.
 */
const dir =
  process.argv[2] ??
  process.env.AMI_ANN_DIR ??
  `${process.env.HOME}/scrb-dev-assets/downloads/ami/ann`;
const here = dirname(fileURLToPath(import.meta.url));
const outFile = process.argv[3] ?? join(here, 'results/slice1-tables.md');

const pct = (a: number, b: number): string => (b === 0 ? 'n/a' : `${((100 * a) / b).toFixed(1)}%`);
const median = (v: number[]): string =>
  v.length === 0
    ? 'n/a'
    : [...v].sort((a, b) => a - b)[Math.floor(v.length / 2)]!.toFixed(0) + ' s';

const started = Date.now();
const configs = [
  { name: 'Package defaults (plan behaviours: refuse weak matches, allow jump back)', tuning: {} },
  {
    name: 'AMI-tuned (not the defaults; places almost everything under the order prior)',
    tuning: AMI_TUNED,
  },
];
const runs = configs.map((c) => ({ ...c, ...evaluate(dir, c.tuning) }));
const { used, skipped } = runs[0]!;
const seconds = ((Date.now() - started) / 1000).toFixed(1);
const lines: string[] = [];
lines.push('# Outline matcher: slice 1 accuracy (Level A, AMI)', '');
lines.push(
  `Generated by \`npm run eval -w @scrb/outline\`. ${used} AMI meetings used (${skipped} skipped: no topic annotation or fewer than 2 headings). Run time ${seconds} s.`,
  '',
);
lines.push(
  'Reference: the AMI topic segmentation of each meeting, turned into an outline (top-level topics as headings, nested topics as subheadings, in order of first appearance). Opening, closing, agenda/equipment and chit-chat topics have no heading, so their dialog is correct only if it stays Not placed. The transcript is the AMI reference transcript (human-written), not speech-recognition output.',
  '',
);
lines.push(
  'Variants: **inOrder** as annotated; **jumpBack** headings 2 and 3 swapped; **deletedHeading** the middle heading removed (its dialog should be Not placed); **extraHeading** one invented unrelated heading added (nothing should land in it).',
  '',
);
const cols =
  '| Group | Meetings | Time-weighted accuracy | Accuracy on dialog that has a heading | Likely-labelled correct | Likely share of time | Unsure share | Not-placed share | Accuracy if unsure counts as not placed | Median boundary error | Meetings under 70% |';
const sep = '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |';
for (const run of runs) {
  lines.push(`# ${run.name}`, '');
  const results = run.results;
  for (const kind of ['all', 'ontology labels', 'free-text labels']) {
    lines.push(`## ${kind === 'all' ? 'All meetings' : `Meetings with ${kind}`}`, '', cols, sep);
    for (const name of VARIANTS) {
      const t = results.get(`${name}|${kind}`);
      if (!t) continue;
      lines.push(
        `| ${name} | ${t.meetings} | ${pct(t.correct, t.ms)} | ${pct(t.inOutlineCorrect, t.inOutlineMs)} | ${pct(t.likelyCorrect, t.likelyMs)} | ${pct(t.likelyMs, t.ms)} | ${pct(t.unsureMs, t.ms)} | ${pct(t.notPlacedMs, t.ms)} | ${pct(t.strictCorrect, t.ms)} | ${median(t.boundaryErrorsSec)} | ${t.meetingAcc.filter((a) => a < 0.7).length} |`,
      );
    }
    lines.push('');
  }
}
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n'));
console.log(lines.join('\n'));
